def check_prose():
    """正文检查：同上，只是 citations 留空，把炮火集中在正文那条路径上"""
    ok = bad = 0
    for c in PROSE_CASES:
        got_pass, notes = _validate([], c.get("资料", HITS), c.get("回答", ""), c.get("问题", ""))
        problems = []
        if got_pass != c["通过"]:
            problems.append(f"期望{'通过' if c['通过'] else '不通过'}，实际{'通过' if got_pass else '不通过'}")
        if c.get("含") and not any(c["含"] in n for n in notes):
            problems.append(f"说明里没提到「{c['含']}」，实际：{notes}")
        if c.get("不含") and any(c["不含"] in n for n in notes):
            problems.append(f"说明里不该出现「{c['不含']}」，实际：{notes}")
        if "条数" in c and len(notes) != c["条数"]:
            problems.append(f"期望 {c['条数']} 条说明，实际 {len(notes)} 条：{notes}")

        if problems:
            bad += 1
            print(f"  ✗ {c['说明']}")
            for p in problems:
                print(f"      {p}")
        else:
            ok += 1
            print(f"  ✓ {c['说明']}")
    return ok, bad


def main():
    print("一、citations 字段")
    ok = bad = 0
    for desc, cites, want_pass, want_note in CASES:
        got_pass, notes = _validate(cites, HITS)
        problems = []
        if got_pass != want_pass:
            problems.append(f"期望{'通过' if want_pass else '不通过'}，实际{'通过' if got_pass else '不通过'}")
        if want_note and not any(want_note in n for n in notes):
            problems.append(f"说明里没提到「{want_note}」，实际：{notes}")

        if problems:
            bad += 1
            print(f"  ✗ {desc}")
            for p in problems:
                print(f"      {p}")
        else:
            ok += 1
            print(f"  ✓ {desc}")

    print("\n二、回答正文里的条号")
    ok2, bad2 = check_prose()
    ok, bad = ok + ok2, bad + bad2

    print(f"\n{ok}/{ok + bad} 通过")
    if bad:
        print(f"★ 有 {bad} 个用例失败 —— 校验器的兜底逻辑有问题")
        return 1
    print("校验器对已知的坏引用都能识别（citations 字段 + 回答正文）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
